import subprocess, re
from collections import Counter, defaultdict

result = subprocess.run(["find", "content/posts", "-name", "*.md"], capture_output=True, text=True)
files = result.stdout.strip().split("\n")

target = []
for f in files:
    with open(f) as fh:
        front = fh.read(500)
    m = re.search(r'^date:\s*["\']?(\d{4})-\d{2}-\d{2}', front, re.MULTILINE)
    if m and m.group(1) >= "2021":
        target.append(f)

all_refs = []
for f in target:
    with open(f) as fh:
        text = fh.read()
    refs = re.findall(r'《([^》]{2,})》([^。]{0,200})', text)
    for title, context in refs:
        author = ""
        am = re.search(r'作者[:：]?\s*([^,，。]+)', context)
        if am:
            author = am.group(1).strip()
        all_refs.append((title, author, context[:200], f))

